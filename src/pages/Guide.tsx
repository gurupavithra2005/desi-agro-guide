function GuideAccordion({ section, language, labels }: { section: GuideSection; language: AppLanguage; labels: typeof pageLabels['en'] }) {
  const [isOpen, setIsOpen] = useState(false);
  const navigate = useNavigate();
  const Icon = section.icon;

  return (
    <Card className="overflow-hidden">
      <button
        onClick={() => setIsOpen(!isOpen)}
        className="w-full p-4 flex items-center gap-3 text-left hover:bg-secondary/50 transition-colors"
      >
        <div className="w-10 h-10 rounded-xl bg-primary/10 flex items-center justify-center shrink-0">
          <Icon className="w-5 h-5 text-primary" />
        </div>
        <div className="flex-1 min-w-0">
          <h3 className="font-semibold text-foreground">{section.titles[language]}</h3>
          <p className="text-xs text-muted-foreground line-clamp-1">{section.descriptions[language]}</p>
        </div>
        {isOpen ? <ChevronUp className="w-5 h-5 text-muted-foreground shrink-0" /> : <ChevronDown className="w-5 h-5 text-muted-foreground shrink-0" />}
      </button>

      {isOpen && (
        <CardContent className="px-4 pb-4 pt-0 space-y-4 border-t border-border">
          {/* Description */}
          <p className="text-sm text-muted-foreground pt-3">{section.descriptions[language]}</p>

          {/* Steps */}
          <div>
            <h4 className="text-sm font-semibold text-foreground mb-2 flex items-center gap-2">
              <Sparkles className="w-4 h-4 text-primary" />
              {labels.howToUse}
            </h4>
            <ol className="space-y-2">
              {section.steps[language].map((step, idx) => (
                <li key={idx} className="flex items-start gap-2">
                  <span className="w-6 h-6 bg-primary/10 text-primary rounded-full flex items-center justify-center text-xs font-bold shrink-0 mt-0.5">
                    {idx + 1}
                  </span>
                  <span className="text-sm text-foreground">{step}</span>
                </li>
              ))}
            </ol>
          </div>

          {/* How it works */}
          <div className="bg-secondary/50 rounded-lg p-3">
            <h4 className="text-sm font-semibold text-foreground mb-1">⚙️ {labels.howItWorks}</h4>
            <p className="text-sm text-muted-foreground">{section.howItWorks[language]}</p>
          </div>

          {/* Tip */}
          <div className="bg-warning/10 border border-warning/20 rounded-lg p-3">
            <p className="text-sm">{section.tip[language]}</p>
          </div>

          {/* Go to feature button */}
          <Button
            variant="outline"
            className="w-full gap-2"
            onClick={() => navigate(section.path)}
          >
            {section.titles[language]}
            <ArrowRight className="w-4 h-4" />
          </Button>
        </CardContent>
      )}
    </Card>
  );
}

